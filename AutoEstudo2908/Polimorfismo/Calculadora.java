public class Calculadora {

    // Versão para dois números inteiros.
    public int somar(int a, int b) {
        return a + b;
    }

    // Versão para dois números decimais.
    public double somar(double a, double b) {
        return a + b;
    }

    // Versão para três números inteiros.
    public int somar(int a, int b, int c) {
        return a + b + c;
    }
}
